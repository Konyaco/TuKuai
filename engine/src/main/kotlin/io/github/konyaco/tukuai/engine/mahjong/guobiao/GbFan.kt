package io.github.konyaco.tukuai.engine.mahjong.guobiao

/**
 * The 81 fan of Guobiao mahjong (中国麻将竞赛规则), highest first. A hand counts every fan it
 * has, less those a bigger one already includes ([excludes]); it needs [GbRules.minFan] fan,
 * not counting flowers, to win.
 */
enum class GbFan(val fan: Int) {
    // 88
    BIG_FOUR_WINDS(88),
    BIG_THREE_DRAGONS(88),
    ALL_GREEN(88),
    NINE_GATES(88),
    FOUR_KONGS(88),
    SEVEN_SHIFTED_PAIRS(88),
    THIRTEEN_ORPHANS(88),

    // 64
    ALL_TERMINALS(64),
    LITTLE_FOUR_WINDS(64),
    LITTLE_THREE_DRAGONS(64),
    ALL_HONOURS(64),
    FOUR_CONCEALED_PUNGS(64),
    PURE_TERMINAL_CHOWS(64),

    // 48
    QUADRUPLE_CHOW(48),
    FOUR_PURE_SHIFTED_PUNGS(48),

    // 32
    FOUR_PURE_SHIFTED_CHOWS(32),
    THREE_KONGS(32),
    ALL_TERMINALS_AND_HONOURS(32),

    // 24
    SEVEN_PAIRS(24),
    GREATER_HONOURS_KNITTED(24),
    ALL_EVEN_PUNGS(24),
    FULL_FLUSH(24),
    PURE_TRIPLE_CHOW(24),
    PURE_SHIFTED_PUNGS(24),
    UPPER_TILES(24),
    MIDDLE_TILES(24),
    LOWER_TILES(24),

    // 16
    PURE_STRAIGHT(16),
    THREE_SUITED_TERMINAL_CHOWS(16),
    PURE_SHIFTED_CHOWS(16),
    ALL_FIVES(16),
    TRIPLE_PUNG(16),
    THREE_CONCEALED_PUNGS(16),

    // 12
    LESSER_HONOURS_KNITTED(12),
    KNITTED_STRAIGHT(12),
    UPPER_FOUR(12),
    LOWER_FOUR(12),
    BIG_THREE_WINDS(12),

    // 8
    MIXED_STRAIGHT(8),
    REVERSIBLE_TILES(8),
    MIXED_TRIPLE_CHOW(8),
    MIXED_SHIFTED_PUNGS(8),
    CHICKEN_HAND(8),
    LAST_TILE_DRAW(8),
    LAST_TILE_CLAIM(8),
    OUT_WITH_REPLACEMENT(8),
    ROBBING_THE_KONG(8),

    // 6
    ALL_PUNGS(6),
    HALF_FLUSH(6),
    MIXED_SHIFTED_CHOWS(6),
    ALL_TYPES(6),
    MELDED_HAND(6),
    TWO_CONCEALED_KONGS(6),
    TWO_DRAGON_PUNGS(6),

    // 4
    OUTSIDE_HAND(4),
    FULLY_CONCEALED(4),
    TWO_MELDED_KONGS(4),
    LAST_OF_KIND(4),

    // 2
    DRAGON_PUNG(2),
    PREVALENT_WIND(2),
    SEAT_WIND(2),
    CONCEALED_HAND(2),
    ALL_CHOWS(2),
    TILE_HOG(2),
    DOUBLE_PUNG(2),
    TWO_CONCEALED_PUNGS(2),
    CONCEALED_KONG(2),
    ALL_SIMPLES(2),

    // 1
    PURE_DOUBLE_CHOW(1),
    MIXED_DOUBLE_CHOW(1),
    SHORT_STRAIGHT(1),
    TWO_TERMINAL_CHOWS(1),
    PUNG_OF_TERMINALS_OR_HONOURS(1),
    MELDED_KONG(1),
    ONE_VOIDED_SUIT(1),
    NO_HONOURS(1),
    EDGE_WAIT(1),
    CLOSED_WAIT(1),
    SINGLE_WAIT(1),
    SELF_DRAWN(1),
    FLOWER_TILES(1);

    /** The fan this one already includes, which a hand with it does not count again. */
    val excludes: Set<GbFan> get() = EXCLUDES[this].orEmpty()

    /** The language key of its name. */
    val key: String get() = "tukuai.guobiao.fan.${name.lowercase()}"

    companion object {
        private val EXCLUDES: Map<GbFan, Set<GbFan>> = mapOf(
            BIG_FOUR_WINDS to setOf(BIG_THREE_WINDS, LITTLE_FOUR_WINDS, ALL_PUNGS, PREVALENT_WIND, SEAT_WIND),
            BIG_THREE_DRAGONS to setOf(LITTLE_THREE_DRAGONS, TWO_DRAGON_PUNGS, DRAGON_PUNG),
            ALL_GREEN to setOf(HALF_FLUSH),
            NINE_GATES to setOf(FULL_FLUSH, FULLY_CONCEALED, CONCEALED_HAND, NO_HONOURS),
            FOUR_KONGS to setOf(THREE_KONGS, TWO_MELDED_KONGS, TWO_CONCEALED_KONGS, MELDED_KONG, CONCEALED_KONG, ALL_PUNGS, SINGLE_WAIT),
            SEVEN_SHIFTED_PAIRS to setOf(SEVEN_PAIRS, FULL_FLUSH, FULLY_CONCEALED, CONCEALED_HAND, SINGLE_WAIT, NO_HONOURS),
            THIRTEEN_ORPHANS to setOf(ALL_TYPES, FULLY_CONCEALED, CONCEALED_HAND, SINGLE_WAIT, ALL_TERMINALS_AND_HONOURS),
            ALL_TERMINALS to setOf(ALL_TERMINALS_AND_HONOURS, ALL_PUNGS, OUTSIDE_HAND, NO_HONOURS, DOUBLE_PUNG, TRIPLE_PUNG, PUNG_OF_TERMINALS_OR_HONOURS),
            LITTLE_FOUR_WINDS to setOf(BIG_THREE_WINDS),
            LITTLE_THREE_DRAGONS to setOf(TWO_DRAGON_PUNGS, DRAGON_PUNG),
            ALL_HONOURS to setOf(ALL_TERMINALS_AND_HONOURS, ALL_PUNGS, OUTSIDE_HAND, PUNG_OF_TERMINALS_OR_HONOURS),
            FOUR_CONCEALED_PUNGS to setOf(CONCEALED_HAND, ALL_PUNGS, THREE_CONCEALED_PUNGS, TWO_CONCEALED_PUNGS, FULLY_CONCEALED),
            PURE_TERMINAL_CHOWS to setOf(SEVEN_PAIRS, FULL_FLUSH, ALL_CHOWS, PURE_DOUBLE_CHOW, TWO_TERMINAL_CHOWS, NO_HONOURS),
            QUADRUPLE_CHOW to setOf(PURE_TRIPLE_CHOW, PURE_SHIFTED_PUNGS, PURE_DOUBLE_CHOW, TILE_HOG),
            FOUR_PURE_SHIFTED_PUNGS to setOf(PURE_TRIPLE_CHOW, PURE_SHIFTED_PUNGS, ALL_PUNGS),
            FOUR_PURE_SHIFTED_CHOWS to setOf(PURE_SHIFTED_CHOWS, SHORT_STRAIGHT, TWO_TERMINAL_CHOWS),
            THREE_KONGS to setOf(TWO_MELDED_KONGS, TWO_CONCEALED_KONGS, MELDED_KONG, CONCEALED_KONG),
            ALL_TERMINALS_AND_HONOURS to setOf(ALL_PUNGS, OUTSIDE_HAND, PUNG_OF_TERMINALS_OR_HONOURS),
            SEVEN_PAIRS to setOf(FULLY_CONCEALED, CONCEALED_HAND, SINGLE_WAIT),
            GREATER_HONOURS_KNITTED to setOf(ALL_TYPES, FULLY_CONCEALED, CONCEALED_HAND, SINGLE_WAIT, LESSER_HONOURS_KNITTED),
            ALL_EVEN_PUNGS to setOf(ALL_PUNGS, ALL_SIMPLES, NO_HONOURS),
            FULL_FLUSH to setOf(NO_HONOURS),
            PURE_TRIPLE_CHOW to setOf(PURE_SHIFTED_PUNGS, PURE_DOUBLE_CHOW),
            PURE_SHIFTED_PUNGS to setOf(PURE_TRIPLE_CHOW),
            UPPER_TILES to setOf(UPPER_FOUR, NO_HONOURS),
            MIDDLE_TILES to setOf(ALL_SIMPLES, NO_HONOURS),
            LOWER_TILES to setOf(LOWER_FOUR, NO_HONOURS),
            PURE_STRAIGHT to setOf(SHORT_STRAIGHT, TWO_TERMINAL_CHOWS),
            THREE_SUITED_TERMINAL_CHOWS to setOf(MIXED_DOUBLE_CHOW, TWO_TERMINAL_CHOWS, NO_HONOURS, ALL_CHOWS),
            ALL_FIVES to setOf(ALL_SIMPLES, NO_HONOURS),
            TRIPLE_PUNG to setOf(DOUBLE_PUNG),
            THREE_CONCEALED_PUNGS to setOf(TWO_CONCEALED_PUNGS),
            LESSER_HONOURS_KNITTED to setOf(ALL_TYPES, FULLY_CONCEALED, CONCEALED_HAND, SINGLE_WAIT),
            UPPER_FOUR to setOf(NO_HONOURS),
            LOWER_FOUR to setOf(NO_HONOURS),
            REVERSIBLE_TILES to setOf(ONE_VOIDED_SUIT),
            MIXED_TRIPLE_CHOW to setOf(MIXED_DOUBLE_CHOW),
            LAST_TILE_DRAW to setOf(SELF_DRAWN),
            OUT_WITH_REPLACEMENT to setOf(SELF_DRAWN),
            ROBBING_THE_KONG to setOf(LAST_OF_KIND),
            MELDED_HAND to setOf(SINGLE_WAIT),
            TWO_CONCEALED_KONGS to setOf(CONCEALED_KONG, TWO_CONCEALED_PUNGS),
            TWO_DRAGON_PUNGS to setOf(DRAGON_PUNG),
            FULLY_CONCEALED to setOf(SELF_DRAWN, CONCEALED_HAND),
            TWO_MELDED_KONGS to setOf(MELDED_KONG),
            ALL_CHOWS to setOf(NO_HONOURS),
            ALL_SIMPLES to setOf(NO_HONOURS),
        )
    }
}
